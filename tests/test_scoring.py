"""Parity tests: the Python scoring must match the HTML prototype exactly.

tests/expected_results.json was generated by running the prototype's JavaScript
(reference/intake_prototype.html) against the same scenarios.
"""
import copy
import json
from pathlib import Path

import pytest

from assessment.scoring import handoff_note, score

DATA = json.loads((Path(__file__).parent / "expected_results.json").read_text())
EXAMPLE = DATA["example"]


@pytest.mark.parametrize("name", list(DATA["scenarios"].keys()))
def test_matches_prototype(name):
    sc = DATA["scenarios"][name]
    answers = copy.deepcopy(EXAMPLE)
    answers.update(sc["overrides"])
    r = score(answers)
    for k in ("isa", "ava", "rt"):
        assert [r.tracks[k].total, r.tracks[k].route] == sc[k], f"{name}: {k}"
    assert r.picks == sc["picks"]
    assert len(r.flags) == sc["flags"]
    assert r.why == sc["why"]


def test_area_totals_add_up():
    r = score(EXAMPLE)
    for t in r.tracks.values():
        assert sum(t.areas.values()) == t.total
        assert 0 <= t.total <= 100


def test_handoff_note_contains_key_lines():
    r = score(EXAMPLE)
    note = handoff_note(EXAMPLE, r)
    assert note.startswith("IDENTITY & AI ASSESSMENTS")
    assert "Cisco PAM: Alex Tan" in note
    assert "RECOMMENDED: AVA, THEN ISA, THEN AI RED TEAMING" in note


def test_handoff_note_matches_prototype_exactly():
    expected = (Path(__file__).parent / "expected_handoff_note.txt").read_text()
    assert handoff_note(EXAMPLE, score(EXAMPLE)) == expected
